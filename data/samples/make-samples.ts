/**
 * Regenerates the synthetic sample files. Run with: npx tsx data/samples/make-samples.ts
 * Every file here is generated from a seeded PRNG; no real person's data is involved.
 */
import { writeFileSync } from "node:fs";
import { syntheticSites, randomPerson, child, toKit, toTwentyThreeAndMeText, type SyntheticSite } from "@lineage/core";
import { TRAITS } from "@lineage/kb";

// Synthetic sites plus the real knowledge-base markers (real rsIDs and build-37 positions),
// with allele frequencies taken from the 1000 Genomes EUR super-population, so the trait
// demo runs on the samples. The people remain entirely fictional.
const sites: SyntheticSite[] = [
  ...syntheticSites(250, 2026),
  ...TRAITS.map((t) => {
    const eff = t.frequencies.find((f) => f.population.endsWith("EUR") && f.allele === t.effectAllele)?.frequency ?? 0.5;
    const other = t.alleles.find((a) => a !== t.effectAllele)!;
    return { rsid: t.rsid, chrom: t.chrom, pos: t.pos37!, a: t.effectAllele, b: other, p: eff };
  }),
];
const grandmother = randomPerson(sites, 1, "F");
const grandfather = randomPerson(sites, 2, "M");
const mother = child(grandmother, grandfather, 3, "F");
const father = randomPerson(sites, 4, "M");
const tester = child(mother, father, 5, "M");
const sibling = child(mother, father, 6, "F");
const auntSpouse = randomPerson(sites, 7, "M");
const aunt = child(grandmother, grandfather, 8, "F");
const cousin = child(aunt, auntSpouse, 9, "F");
const stranger = randomPerson(sites, 10, "F");

const files: Record<string, ReturnType<typeof toKit>> = {
  "tester.txt": toKit(tester, { seed: 11 }),
  "sibling.txt": toKit(sibling, { seed: 12 }),
  "mother.txt": toKit(mother, { seed: 13 }),
  "cousin.txt": toKit(cousin, { seed: 14 }),
  "unrelated.txt": toKit(stranger, { seed: 15 }),
};
for (const [name, kit] of Object.entries(files)) {
  writeFileSync(new URL(`./${name}`, import.meta.url), toTwentyThreeAndMeText(kit, `# SYNTHETIC sample generated by Lineage (data/samples/make-samples.ts). Not a real person.\n# Layout follows the 23andMe raw data format on build 37.`));
}

