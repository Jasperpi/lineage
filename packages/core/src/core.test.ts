describe("supervised admixture", () => {
  const panel = syntheticPanel(sites, 5);
  const freqOf = (popIdx: number) => {
    const byRsid = new Map(panel.snps.map((s) => [s.rsid, s]));
    return (s: { rsid: string; a: string }) => { const p = byRsid.get(s.rsid); return p ? p.freq[popIdx]! : 0.5; };
  };
  it("recovers a pure-population individual", () => {
    const p1 = toKit(randomPerson(sites, 41, "F", freqOf(0)), { errorRate: 0 });
    const r = estimateAdmixture(p1, panel, { bootstrapReplicates: 20 });
    expect(r.proportions[0]!).toBeGreaterThan(0.93);
    expect(r.snpsUsed).toBeGreaterThan(6000);
  });
  it("recovers a 50/50 first-generation admixed individual within a few percent", () => {
    const a = randomPerson(sites, 42, "F", freqOf(0));
    const b = randomPerson(sites, 43, "M", freqOf(1));
    const mixed = toKit(child(a, b, 44, "F"), { errorRate: 0 });
    const r = estimateAdmixture(mixed, panel, { bootstrapReplicates: 20 });
    expect(r.proportions[0]!).toBeGreaterThan(0.44);
    expect(r.proportions[0]!).toBeLessThan(0.56);
    expect(r.ci95[0]![0]).toBeLessThan(r.proportions[0]!);
    expect(r.ci95[0]![1]).toBeGreaterThan(r.proportions[0]!);
  });
  it("recovers a 75/25 second-generation mixture", () => {
    const a = randomPerson(sites, 52, "F", freqOf(0));
    const b = randomPerson(sites, 53, "M", freqOf(1));
    const half = child(a, b, 54, "M");
    const c = randomPerson(sites, 55, "F", freqOf(0));
    const q = toKit(child(c, half, 56, "F"), { errorRate: 0 });
    const r = estimateAdmixture(q, panel, { bootstrapReplicates: 20 });
    expect(r.proportions[0]!).toBeGreaterThan(0.68);
    expect(r.proportions[0]!).toBeLessThan(0.82);
  });
});

