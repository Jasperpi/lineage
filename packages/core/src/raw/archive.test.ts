import { describe, expect, it } from "vitest";
import { deflateRawSync, gzipSync } from "node:zlib";
import { openRawText, parseRawKit } from "../index.js";

const RAW = "# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\nrs3094315\t1\t752566\tAG\nrs12562034\t1\t768448\tGG\n";

/** A minimal zip archive (one or more deflated entries), written byte by byte. */
function zip(files: Array<[string, string]>): Uint8Array {
  const parts: Buffer[] = [], central: Buffer[] = [];
  let offset = 0;
  for (const [name, text] of files) {
    const raw = Buffer.from(text), comp = deflateRawSync(raw), nm = Buffer.from(name);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(8, 8);
    local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(raw.length, 22); local.writeUInt16LE(nm.length, 26);
    const cd = Buffer.alloc(46);
    cd.writeUInt32LE(0x02014b50, 0); cd.writeUInt16LE(20, 4); cd.writeUInt16LE(20, 6); cd.writeUInt16LE(8, 10);
    cd.writeUInt32LE(comp.length, 20); cd.writeUInt32LE(raw.length, 24); cd.writeUInt16LE(nm.length, 28); cd.writeUInt32LE(offset, 42);
    parts.push(local, nm, comp);
    central.push(cd, nm);
    offset += 30 + nm.length + comp.length;
  }
  const cdBuf = Buffer.concat(central);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0); eocd.writeUInt16LE(files.length, 8); eocd.writeUInt16LE(files.length, 10);
  eocd.writeUInt32LE(cdBuf.length, 12); eocd.writeUInt32LE(offset, 16);
  return new Uint8Array(Buffer.concat([...parts, cdBuf, eocd]));
}

describe("opening compressed raw files", () => {
  it("reads plain text unchanged", async () => {
    const r = await openRawText(new TextEncoder().encode(RAW));
    expect(r.compressed).toBeUndefined();
    expect(r.text).toBe(RAW);
  });

  it("inflates gzip", async () => {
    const r = await openRawText(new Uint8Array(gzipSync(RAW)));
    expect(r.compressed).toBe("gzip");
    expect(parseRawKit(r.text).report.rowsKept).toBe(2);
  });

  it("finds the largest text entry in a vendor-style zip and skips macOS metadata", async () => {
    const r = await openRawText(zip([["README.txt", "hello"], ["__MACOSX/._genome.txt", "x".repeat(900)], ["genome_Full_20260101.txt", RAW]]));
    expect(r.compressed).toBe("zip");
    expect(r.entry).toBe("genome_Full_20260101.txt");
    expect(parseRawKit(r.text).kit.get("rs3094315")?.genotype).toBe("AG");
  });

  it("explains a zip with no text file", async () => {
    await expect(openRawText(zip([["photo.jpg", "not dna"]]))).rejects.toThrow(/No .txt or .csv/);
  });
});
