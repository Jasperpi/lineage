/**
 * Synthetic data for tests and demos. Nothing here is a real person: genotypes
 * are drawn from a seeded PRNG, optionally from reference frequencies, and
 * relatives are simulated by literal Mendelian transmission with recombination.
 */
import { AUTOSOMES, type Chrom, GRCH37_LENGTH } from "./genome.js";
import { Kit, type KitMeta, type Variant } from "./kit/kit.js";
import { mulberry32 } from "./util/random.js";
import type { ReferencePanel, PanelSnp } from "./admixture/supervised.js";

const META: KitMeta = { format: "23andme", build: 37, headerLines: ["# Synthetic kit generated by Lineage; not a real person"], strand: "plus" };

export interface SyntheticSite { rsid: string; chrom: Chrom; pos: number; a: string; b: string; /** frequency of allele a */ p: number }

/** Deterministic site list spread evenly across the autosomes and X. */
export function syntheticSites(nPerChrom = 400, seed = 1, includeX = true): SyntheticSite[] {
  const rng = mulberry32(seed);
  const out: SyntheticSite[] = [];
  const chroms: Chrom[] = includeX ? [...AUTOSOMES, "X"] : [...AUTOSOMES];
  const pairs: Array<[string, string]> = [["A", "G"], ["C", "T"], ["A", "C"], ["G", "T"]];
  let id = 1000;
  for (const c of chroms) {
    const len = GRCH37_LENGTH[c];
    for (let i = 0; i < nPerChrom; i++) {
      const [a, b] = pairs[Math.floor(rng() * pairs.length)]!;
      out.push({ rsid: `syn${id++}`, chrom: c, pos: Math.floor(((i + 0.5) / nPerChrom) * len), a, b, p: 0.1 + 0.8 * rng() });
    }
  }
  return out;
}

/** Two haplotypes per site, so relatives can be simulated by transmission. */
export interface Haplotypes { sites: SyntheticSite[]; h1: string[]; h2: string[]; sex: "M" | "F" }

export function randomPerson(sites: SyntheticSite[], seed: number, sex: "M" | "F" = "F", freqs?: (s: SyntheticSite, i: number) => number): Haplotypes {
  const rng = mulberry32(seed);
  const h1: string[] = [], h2: string[] = [];
  sites.forEach((s, i) => {
    const p = freqs ? freqs(s, i) : s.p;
    h1.push(rng() < p ? s.a : s.b);
    h2.push(rng() < p ? s.a : s.b);
  });
  return { sites, h1, h2, sex };
}

/** Meiosis: one recombinant haplotype from a parent, ~1 crossover per 100 Mb (approximate). */
export function gamete(parent: Haplotypes, seed: number): string[] {
  const rng = mulberry32(seed);
  const out: string[] = [];
  let useFirst = rng() < 0.5;
  let lastChrom: Chrom | undefined, lastPos = 0;
  parent.sites.forEach((s, i) => {
    if (s.chrom !== lastChrom) { useFirst = rng() < 0.5; lastChrom = s.chrom; lastPos = s.pos; }
    else {
      const dist = s.pos - lastPos;
      if (rng() < dist / 100_000_000) useFirst = !useFirst;
      lastPos = s.pos;
    }
    out.push(useFirst ? parent.h1[i]! : parent.h2[i]!);
  });
  return out;
}

export function child(mother: Haplotypes, father: Haplotypes, seed: number, sex: "M" | "F" = "F"): Haplotypes {
  return { sites: mother.sites, h1: gamete(mother, seed), h2: gamete(father, seed + 1), sex };
}

export function toKit(p: Haplotypes, opts: { noCallRate?: number; errorRate?: number; seed?: number } = {}): Kit {
  const rng = mulberry32(opts.seed ?? 99);
  const noCall = opts.noCallRate ?? 0.005, err = opts.errorRate ?? 0.001;
  const rows: Variant[] = p.sites.map((s, i) => {
    let g: string;
    if (rng() < noCall) g = "";
    else if (s.chrom === "X" && p.sex === "M") g = p.h1[i]!; // hemizygous
    else {
      let a = p.h1[i]!, b = p.h2[i]!;
      if (rng() < err) a = a === s.a ? s.b : s.a;
      g = [a, b].sort().join("");
    }
    return { rsid: s.rsid, chrom: s.chrom, pos: s.pos, genotype: g };
  });
  if (p.sex === "M") for (let i = 0; i < 300; i++) rows.push({ rsid: `synY${i}`, chrom: "Y", pos: 2_800_000 + i * 50_000, genotype: rng() < 0.9 ? "A" : "" });
  else for (let i = 0; i < 300; i++) rows.push({ rsid: `synY${i}`, chrom: "Y", pos: 2_800_000 + i * 50_000, genotype: "" });
  return new Kit({ ...META }, rows);
}

/** A two-population synthetic reference panel with divergent frequencies, for admixture tests. */
export function syntheticPanel(sites: SyntheticSite[], seed = 5, populations = ["POP1", "POP2"]): ReferencePanel {
  const rng = mulberry32(seed);
  const snps: PanelSnp[] = sites.filter((s) => s.chrom !== "X").map((s) => ({
    rsid: s.rsid, chrom: s.chrom, pos: s.pos, allele: s.a, other: s.b,
    freq: populations.map(() => Math.min(0.95, Math.max(0.05, rng()))),
  }));
  return { name: "synthetic", build: 37, populations, snps, source: { name: "synthetic", url: "", retrieved: "n/a" } };
}
